"""Data-quality assessment of the raw Coveo tables.

Coveo's documentation is unusually candid: "front-end tracking is by nature
imperfect, so small inconsistencies are to be expected", and "the order of the
events in the file is not strictly chronological".

Most portfolio projects quote that line and move on. This module *measures* it.
Every check below turns a warning in the docs into a number, so that later
modelling decisions (how to order events, whether to trust a purchase without a
preceding add, how to treat a click on a SKU that was never returned) rest on
observed rates rather than assumptions.

Output: reports/data_quality_report.md
"""
from __future__ import annotations


import time
from datetime import datetime, timezone

from src import config
from src.ingest.build_duckdb import connect

MINUTE_MS = 60 * 1000
SESSION_GAP_MS = config.SESSION_GAP_MINUTES * MINUTE_MS


class Report:
    """Accumulates markdown sections and the headline numbers."""

    def __init__(self) -> None:
        self.sections: list[str] = []
        self.findings: list[tuple[str, str]] = []

    def add(self, markdown: str) -> None:
        self.sections.append(markdown.rstrip())

    def finding(self, severity: str, text: str) -> None:
        """severity in {'blocker', 'handle', 'note'}."""
        self.findings.append((severity, text))

    def render(self) -> str:
        icons = {"blocker": "🔴", "handle": "🟠", "note": "🔵"}
        head = [
            "# Data Quality Assessment — Coveo SIGIR 2021 eCommerce Dataset",
            "",
            "Generated by `src/profiling/data_quality.py` on "
            f"{datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC.",
            "",
            "> Dataset © Coveo Solutions Inc., released for the SIGIR 2021 eCom Data",
            "> Challenge and used here under their research/educational Terms &",
            "> Conditions. No row-level data is reproduced in this report — only",
            "> aggregate counts and rates.",
            "",
            "---",
            "",
            "## Findings summary",
            "",
        ]
        if self.findings:
            head.append("| | Finding |")
            head.append("|---|---|")
            for sev, text in self.findings:
                head.append(f"| {icons.get(sev, '•')} | {text} |")
        else:
            head.append("_No findings recorded._")
        head += ["", "🔴 blocks analysis · 🟠 must be handled in modelling · "
                     "🔵 worth knowing", "", "---", ""]
        return "\n".join(head) + "\n" + "\n\n".join(self.sections) + "\n"


def block(text: str) -> str:
    """Dedent a section template.

    textwrap.dedent cannot be used directly here: it runs on the *interpolated*
    f-string, and interpolated tables start at column 0, so the common leading
    prefix collapses to "" and nothing is stripped. Every template in this
    module is indented by exactly 8 spaces, so strip that much from the lines
    that have it and leave interpolated content alone.
    """
    return "\n".join(
        line[8:] if line.startswith(" " * 8) else line
        for line in text.split("\n")
    ).strip()


def md_table(headers: list[str], rows: list[tuple]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join(["---"] * len(headers)) + "|"]
    for r in rows:
        cells = []
        for v in r:
            if isinstance(v, float):
                cells.append(f"{v:,.2f}")
            elif isinstance(v, int):
                cells.append(f"{v:,}")
            else:
                cells.append("_NULL_" if v is None else str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def pct(part: float, whole: float) -> float:
    return 0.0 if not whole else 100.0 * part / whole


